export function releaseHistory(currentVersion=APP_VERSION,repository=UPDATE_REPOSITORY){
  const repo=repositoryName(repository);compareVersions(currentVersion,currentVersion);
  return {currentVersion,records:records.map(record=>{
    const development=!record.date&&record.version!==currentVersion;
    return{...structuredClone(record),status:development?"development":record.version===currentVersion?"current":compareVersions(record.version,currentVersion)>0?"available":"previous",
      url:development?null:`https://github.com/${repo}/releases/tag/${record.version}`};
  })};
}
export function releaseNotesFor(version){
  const record=records.find(record=>record.version===version);if(!record)throw Error("릴리스 기능 내역이 없습니다. src/release-history.mjs에 해당 버전의 변경 사항을 등록하세요.");
  return `## ${record.title}\n\n`+record.groups.map(group=>`### ${group.title}\n\n`+group.items.map(item=>"- "+item).join("\n")).join("\n\n");
}
